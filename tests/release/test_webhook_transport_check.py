"""tools/webhook_transport_check.py: the webhook transport enablement precondition refuses unless all checks hold.

Executors here are parser fixtures (shell scripts printing `zabbix_server -V` text), not executions of real
Zabbix builds; TLS cases use loopback servers with a test CA generated by the openssl CLI. The check itself makes
a real TLS handshake with Python's ssl module.
"""
import json
import os
from pathlib import Path
import shutil
import socket
import ssl
import subprocess
import threading

import pytest

import webhook_transport_check as check

ROOT = Path(__file__).resolve().parents[2]


def fake_server(tmp_path, first, second='Revision e7da53eea21 22 September 2026, compilation time: Sep 22 2026 06:34:47'):
    binary = tmp_path / ('zabbix_server-' + str(abs(hash((first, second)))))
    binary.write_text(f"#!/bin/sh\nprintf '%s\\n%s\\n' '{first}' '{second}'\n")
    binary.chmod(0o755)
    return str(binary)


@pytest.mark.parametrize('first, second, ok', [
    ('zabbix_server (Zabbix) 7.0.31', 'Revision e7da53eea21 22 September 2026, compilation time: Sep 22 2026 06:34:47', True),
    ('zabbix_server (Zabbix) 7.0.31', 'Revision 0123456789a 22 September 2026, compilation time: x', False),   # other source
    ('zabbix_server (Zabbix) 7.0.27', 'Revision e7da53eea21 22 September 2026, compilation time: x', False),   # ignores the options
    ('zabbix_server (Zabbix) 7.0.32', 'Revision e7da53eea21 22 September 2026, compilation time: x', False),   # not qualified
    ('zabbix_server (Zabbix) 7.2.12', 'Revision e7da53eea21 22 September 2026, compilation time: x', False),   # other branch
    ('zabbix_server (Zabbix) 7.0.31rc1', 'Revision e7da53eea21 22 September 2026, compilation time: x', False),
    ('not zabbix', '', False),
])
def test_only_a_qualified_executor_build_is_accepted(tmp_path, first, second, ok):
    result = check.executor(fake_server(tmp_path, first, second))
    assert result['ok'] is ok and (ok or result['reason'] == 'executor_not_qualified')


def test_an_unreadable_executor_is_refused(tmp_path):
    assert check.executor(str(tmp_path / 'absent'))['reason'].startswith('executor_unreadable')


def export(tmp_path, script):
    path = tmp_path / 'export.json'
    path.write_text(json.dumps({'zabbix_export': {'media_types': [{'name': 'Zab-al-ack source contract v1 REFERENCE DISABLED',
                                                                   'type': 'WEBHOOK', 'script': script}]}}))
    return path


def test_the_stored_script_must_equal_the_reviewed_artifact(tmp_path):
    reviewed = (ROOT / 'zabbix/v1/webhook.js').read_text()
    assert 'new HttpRequest({SSLVerifyPeer: true, SSLVerifyHost: true})' in reviewed
    assert check.script(export(tmp_path, reviewed.replace('\n', '\r\n')))['ok'] is True  # Zabbix stores CRLF
    unverified = reviewed.replace('new HttpRequest({SSLVerifyPeer: true, SSLVerifyHost: true})', 'new HttpRequest()')
    assert check.script(export(tmp_path, unverified))['reason'] == 'media_script_differs_from_the_reviewed_artifact'
    assert check.script(tmp_path / 'absent.json')['reason'] == 'media_export_unreadable'


@pytest.fixture(scope='module')
def pki(tmp_path_factory):
    if not shutil.which('openssl'):
        pytest.skip('openssl CLI unavailable')
    d = tmp_path_factory.mktemp('pki')

    def sh(*args):
        subprocess.run(args, cwd=d, check=True, capture_output=True)
    for ca in ('trusted', 'untrusted'):
        sh('openssl', 'req', '-x509', '-newkey', 'rsa:2048', '-nodes', '-days', '2', '-subj', f'/CN={ca}-ca', '-keyout', f'{ca}-ca.key',
           '-out', f'{ca}-ca.pem', '-addext', 'basicConstraints=critical,CA:TRUE', '-addext', 'keyUsage=critical,keyCertSign')

    def leaf(name, host, ca, days='1', start=None):
        sh('openssl', 'req', '-newkey', 'rsa:2048', '-nodes', '-subj', '/CN=' + host, '-keyout', name + '.key', '-out', name + '.csr')
        (d / (name + '.ext')).write_text(f'subjectAltName=DNS:{host}\n')
        extra = ['-not_before', start, '-not_after', '20000102000000Z'] if start else ['-days', days]
        sh('openssl', 'x509', '-req', '-in', name + '.csr', '-CA', ca + '-ca.pem', '-CAkey', ca + '-ca.key', '-CAcreateserial',
           '-extfile', name + '.ext', '-out', name + '.pem', *extra)
    leaf('good', 'localhost', 'trusted')
    leaf('other-anchor', 'localhost', 'untrusted')
    leaf('wrong-name', 'elsewhere.invalid', 'trusted')
    try:
        leaf('expired', 'localhost', 'trusted', start='20000101000000Z')
    except subprocess.CalledProcessError:
        pass  # openssl < 3.4 lacks -not_before; the expired case is skipped
    ca_dir = d / 'store'
    ca_dir.mkdir()
    shutil.copy(d / 'trusted-ca.pem', ca_dir / 'ca-certificates.crt')
    return d


def serve(pki, name):
    context = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
    context.load_cert_chain(pki / (name + '.pem'), pki / (name + '.key'))
    listener = socket.create_server(('127.0.0.1', 0))
    port = listener.getsockname()[1]
    requests = []

    def accept():
        for _ in range(4):
            try:
                connection, _ = listener.accept()
            except OSError:
                return
            try:
                with context.wrap_socket(connection, server_side=True) as tls:
                    tls.settimeout(2)
                    requests.append(tls.recv(1))  # any HTTP byte would be a request; the check sends none
            except (OSError, ssl.SSLError):
                pass
    threading.Thread(target=accept, daemon=True).start()
    return port, requests, listener


@pytest.mark.parametrize('name, ok, reason', [
    ('good', True, None),
    ('other-anchor', False, 'certificate_not_verified'),   # missing trust anchor
    ('wrong-name', False, 'certificate_not_verified'),
    ('expired', False, 'certificate_not_verified'),
])
def test_trust_is_a_verified_handshake_against_the_executor_store_and_sends_nothing(pki, name, ok, reason):
    if not (pki / (name + '.pem')).exists():
        pytest.skip('this openssl cannot issue an expired certificate')
    port, requests, listener = serve(pki, name)
    try:
        result = check.trust(f'https://localhost:{port}/api/alert', str(pki / 'store/ca-certificates.crt'), str(pki / 'store'))
    finally:
        listener.close()
    assert result['ok'] is ok and (ok or result['reason'].startswith(reason))
    assert all(chunk in (b'',) for chunk in requests)  # no HTTP request byte reached the listener


